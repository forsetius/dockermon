const dictionaries: Record<Locale, Record<TranslationKey, string>> = {
  en: english,
  pl: polish,
};

const activeProjectCountForms: Record<Locale, Partial<Record<Intl.LDMLPluralRule, string>>> = {
  en: { other: '{count} active' },
  pl: {
    one: '{count} aktywny',
    few: '{count} aktywne',
    many: '{count} aktywnych',
    other: '{count} aktywnego',
  },
};

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: Record<string, string | number> = {},
): string {
  const template = dictionaries[locale]?.[key] ?? english[key];
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function translateActiveProjectCount(locale: Locale, count: number): string {
  const pluralCategory = new Intl.PluralRules(locale).select(count);
  const localeForms = activeProjectCountForms[locale] ?? activeProjectCountForms.en;
  const template = localeForms[pluralCategory] ?? localeForms.other ?? '{count} active';
  return template.replace('{count}', String(count));
}

export type { TranslationKey };
